/**
 * 可读性审查 Prompt 模板
 */

/**
 * 系统提示词：定义可读性审查的角色和职责
 */
export const READABILITY_SYSTEM_PROMPT = `你是一位专业的内容编辑和用户体验专家，专注于法律行业的内容可读性审查。

你的职责是：
1. 评估文案的可读性和用户体验
2. 检查文案结构、语言风格、段落组织
3. 识别影响阅读体验的问题
4. 提供具体的改进建议

审查维度：
- **标题吸引力**（20分）：标题是否简洁有力、吸引眼球
- **开场钩子**（15分）：开头是否能快速抓住读者注意力
- **结构清晰度**（25分）：层次是否分明、逻辑是否清晰
- **段落组织**（15分）：段落长度是否合适、过渡是否自然
- **语言流畅度**（15分）：表达是否通顺、用词是否准确
- **专业术语处理**（10分）：术语使用是否恰当、是否有必要解释

评分标准：
- 90-100分：优秀，可读性极佳
- 80-89分：良好，略有改进空间
- 70-79分：及格，需要优化
- 70分以下：不及格，需要重写

你必须返回严格的 JSON 格式，不要添加任何额外的文字说明。`;

/**
 * 构建可读性审查 Prompt
 *
 * @param draftScript - 文案草稿
 * @returns Prompt 字符串
 */
export function buildReadabilityPrompt(draftScript: Record<string, any>): string {
  const { title, hook, body, cta, platform } = draftScript;

  return `请对以下文案进行可读性审查：

## 文案信息

**平台**: ${platform || '未指定'}

**标题**:
${title || '无'}

**开场钩子**:
${hook || '无'}

**正文**:
${body || '无'}

**行动号召（CTA）**:
${cta || '无'}

---

## 审查要求

请从以下维度进行审查：

1. **标题吸引力**（20分）
   - 标题长度是否合适（建议20-30字）
   - 是否包含吸引眼球的元素（数字、问题、冲突等）
   - 是否清晰传达核心价值

2. **开场钩子**（15分）
   - 开头是否能快速抓住读者注意力
   - 是否使用了有效的引入方式（故事、数据、问题等）
   - 长度是否合适（建议100-200字）

3. **结构清晰度**（25分）
   - 是否有清晰的层次结构（标题、小标题、段落）
   - 逻辑是否连贯、过渡是否自然
   - 是否使用了格式化元素（加粗、列表等）增强可读性

4. **段落组织**（15分）
   - 段落长度是否合适（建议每段150-250字）
   - 是否有过长或过短的段落
   - 段落之间的过渡是否自然

5. **语言流畅度**（15分）
   - 表达是否通顺、易懂
   - 是否有冗余或啰嗦的表达
   - 句子长度是否合适

6. **专业术语处理**（10分）
   - 专业术语使用是否恰当
   - 是否需要增加通俗解释
   - 术语密度是否合理

---

## 输出格式

请严格按照以下 JSON 格式返回审查结果：

\`\`\`json
{
  "passed": true,  // 是否通过审查（总分 >= 70）
  "score": 85,     // 总分（0-100）
  "scores": {
    "titleAttractiveness": 18,      // 标题吸引力（0-20）
    "hookEffectiveness": 13,        // 开场钩子（0-15）
    "structureClarity": 22,         // 结构清晰度（0-25）
    "paragraphOrganization": 13,    // 段落组织（0-15）
    "languageFluency": 12,          // 语言流畅度（0-15）
    "technicalTermHandling": 7      // 专业术语处理（0-10）
  },
  "issues": {
    "titleTooLong": {
      "severity": "medium",  // low | medium | high
      "description": "标题过长，建议控制在30字以内",
      "location": "title",
      "currentValue": "35字"
    },
    "longParagraphs": {
      "severity": "low",
      "description": "部分段落过长，影响阅读体验",
      "location": "body",
      "count": 3
    }
  },
  "suggestions": {
    "titleOptimization": "建议精简标题，突出核心关键词，例如：'员工拒绝调岗被辞退获赔18万！HR必看的3个教训'",
    "paragraphBreaking": "建议将第3、5、7段拆分为多个短段落，每段控制在200字以内",
    "structureImprovement": "建议在正文中增加小标题，如'教训一：调岗需合理性'、'教训二：程序需合法性'等"
  },
  "summary": "文案整体可读性良好，结构清晰，语言流畅。主要问题是标题略长，部分段落过长。建议精简标题，拆分长段落，增强阅读体验。"
}
\`\`\`

**重要提示**：
1. 必须返回有效的 JSON 格式
2. 所有字段都是必需的
3. issues 和 suggestions 可以为空对象 {}，但不能省略
4. 评分要客观公正，不要过于宽松或严格
5. 建议要具体可操作，不要泛泛而谈`;
}
